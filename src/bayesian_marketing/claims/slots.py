"""J4R: rendered figure slots (spec/Brain_Join_Specification_v0.4.md, J4R, C1 to C7).

The persona's words carry no figure. Every figure is a slot the engine renders whole from a run
quantity, a notebook quantity or a run's comparison record; outside the slots the text must pass
the numeral rule, which is the guarantee. The comparative lint is a fixed word list and is not.
"""

from __future__ import annotations

from collections.abc import Callable
from typing import Any, Literal, TypedDict

SlotKind = Literal["fig", "cmp", "name", "date"]
Form = Literal["full", "start"]


class SlotQuantity(TypedDict):
    name: str
    subject: str
    status: str | None  # estimable | marginal | below_floor | None (observed)


class MenuItem(TypedDict):
    token: str  # the slot as the persona writes it, without "#<claim_id>" and without a form
    kind: SlotKind
    measure: str | None
    subject: str | None
    status: str | None
    newest: bool
    run_id: str | None
    release_id: str | None
    forms: dict[str, str]  # "full" and "start", rendered


class Menu(TypedDict):
    client_id: str
    slots: list[MenuItem]
    reasons: list[str]  # refs that could not be read, by name
    engine_version: str
    checked_at: str


class SlotOut(TypedDict):
    token: str
    ok: bool
    rendered: str | None
    ref: str
    claim_id: str | None
    run_id: str | None
    release_id: str | None
    quantity: SlotQuantity | None
    newest: bool | None
    reasons: list[str]


class Rendered(TypedDict):
    ok: bool
    text: str | None  # None whenever ok is False: never a partial rendering
    template: str
    slots: list[SlotOut]
    reasons: list[str]
    lint: list[str]
    engine_version: str
    inputs_hash: str
    checked_at: str


LoadRun = Callable[[str], Any]
LoadRelease = Callable[[str], tuple[dict[str, Any], list[dict[str, Any]], list[dict[str, Any]]]]
LoadNames = Callable[[str], dict[str, str]]

